#!/system/bin/sh
# ==============================================================================
# 风吟调度 (Fengyin Governor) - 模块卸载善后清理脚本
# 文件: uninstall.sh
# 触发时机: 用户在 Magisk / KernelSU 管理器中点击“移除/卸载”并在下次开机重启时执行
# 核心职责:
#   清理模块运行期间在系统公共目录 (/data) 下生成的外部调度交互文件，
#   避免残留无效文件导致 Scene 或其他调度管理器误报或报错。
# ==============================================================================

# ------------------------------------------------------------------------------
# 后台异步清理逻辑 (避免阻塞 Android 系统正常启动流程)
# ------------------------------------------------------------------------------
{
	# 轮询检测 /data 分区是否已经解密并挂载就绪
	until [ -d /data ]; do
		sleep 1
	done

	# 清理为 Scene / 嘟嘟调度生成的元数据配置文件与主入口脚本
	rm -f /data/powercfg.json
	rm -f /data/powercfg.sh
} & # 放入后台子 shell 异步执行，不占用 Magisk 启动钩子的时间

#!/system/bin/sh
# ==============================================================================
# 风吟调度 (Fengyin Governor) - Magisk/KernelSU 自定义安装脚本
# 文件: customize.sh
# 触发阶段: 用户在 Magisk App 或 Recovery 环境下刷入模块时由 Magisk 框架调用
# 核心职责:
#   1. 检测目标机型的芯片平台 (SoC Model)
#   2. 校验当前模块是否包含该芯片的针对性配置文件 (configs/$soc_model.sh)
#   3. 初始化模块内所有文件的权限 (root:root, 目录 0755, 文件 0644)
#   4. 触发 Scene / 第三方调度切换接口初始化脚本 (init_vtools.sh)
#   5. 将识别出的芯片型号硬编码注入到 power_switch.sh 中以加速后续执行
# ==============================================================================

# ------------------------------------------------------------------------------
# 1. 识别当前设备的 SoC 平台型号
# ------------------------------------------------------------------------------
# 从 Android 系统属性中读取芯片型号 (如 SM8650, SM8550 等)
soc_model=`getprop ro.soc.model`

# 在刷入界面打印交互提示信息
ui_print "处理器的型号为：$soc_model"
sleep 0.5
ui_print "本调度专注于省电，出现卡顿或发热现象请卸载更换其他调度"
sleep 0.5
ui_print "日用省电模式，游戏使用均衡及以上模式"
sleep 1.0
ui_print "刷入完成,🐔你太美"

# ------------------------------------------------------------------------------
# 2. 校验芯片支持性
# ------------------------------------------------------------------------------
# 检查 configs 目录下是否存在与当前芯片型号对应的配置文件
if [ ! -f $MODPATH/configs/$soc_model.sh ]; then
    ui_print "你的处理器不受支持！"
    # 调用 Magisk 内置 abort 函数终止安装，防止缺少配置导致异常
    abort
fi

# ------------------------------------------------------------------------------
# 3. 递归设置模块目录与文件权限
# ------------------------------------------------------------------------------
# 参数说明: set_perm_recursive <目录> <用户UID> <用户组GID> <目录权限> <文件权限>
# 将所有目录设为 0755 (rwxr-xr-x)，普通文件设为 0644 (rw-r--r--)
set_perm_recursive $MODPATH 0 0 0755 0644

# ------------------------------------------------------------------------------
# 4. 生成外部调度器交互配置文件
# ------------------------------------------------------------------------------
# 调用 init_vtools.sh 并传入 module.prop 的绝对物理路径，
# 用于在 /data 目录下生成供 Scene / 嘟嘟调度识别的 powercfg.json 和入口脚本 powercfg.sh
sh $MODPATH/vtools/init_vtools.sh $(realpath $MODPATH/module.prop)

# ------------------------------------------------------------------------------
# 5. 动态注入芯片型号至调度切换主脚本
# ------------------------------------------------------------------------------
# 在 power_switch.sh 的第 4 行插入变量赋值 "soc_model=$soc_model"，
# 避免每次调度切换时重复调用 getprop，提高执行效率
sed -i "4i\soc_model=$soc_model" $MODPATH/power_switch.sh

#!/system/bin/sh
# ==============================================================================
# 风吟调度 (Fengyin Governor) - 开机自启动服务脚本 (Late-start Service)
# 文件: service.sh
# 触发时机: Android 系统启动阶段，数据解密完成且底层服务基本就绪后，由 Magisk 自动触发
# 核心职责:
#   1. 重置模式状态记录文件，确保每次开机为全新初始状态
#   2. 重新初始化并生成 /data/powercfg.json 与 /data/powercfg.sh，
#      防止系统恢复出厂、更新系统或第三方清理误删后调度失效
# ==============================================================================

# 获取模块当前安装目录绝对路径
MODDIR=${0%/*}

# ------------------------------------------------------------------------------
# 1. 重置模式状态记录
# ------------------------------------------------------------------------------
# 删除旧的模式记录文件并重新创建空文件，避免上次关机前的残留状态影响开机调度判断
rm $MODDIR/mode
touch $MODDIR/mode

# ------------------------------------------------------------------------------
# 2. 重新生成外部调度交互接口文件
# ------------------------------------------------------------------------------
# 调用 init_vtools.sh，基于 module.prop 重新生成 /data/powercfg.json 与 /data/powercfg.sh
# 确保 Scene、嘟嘟调度等前端应用开机后能够即刻正常检测并托管本调度
sh $MODDIR/vtools/init_vtools.sh $(realpath $MODDIR/module.prop)
